#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate local.json: map com.vendor.* placeholders to the packages on this device.

  python tools/make_local.py --serial <SN>          # write local.json
  python tools/make_local.py --dry-run              # show the mapping only
  python tools/make_local.py --set com.vendor.calculator=com.example.calc

Placeholders are discovered by scanning the repository, so a newly added one shows up
automatically. Existing entries are preserved; only new placeholders are resolved.
"""
import argparse
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
import uiauto  # noqa: E402
from adbkit import adbkit as kit  # noqa: E402

PLACEHOLDER_RE = re.compile(r"com\.vendor\.[a-z0-9_.]+")
SKIP_DIRS = {".git", "__pycache__", "data", "out"}
TEXT_EXT = {".json", ".py", ".md", ".ps1", ".yml"}


def find_placeholders():
    found = set()
    for root, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for name in files:
            if os.path.splitext(name)[1] not in TEXT_EXT or name == "local.json":
                continue
            path = os.path.join(root, name)
            try:
                text = open(path, encoding="utf-8").read()
            except (OSError, UnicodeDecodeError):
                continue
            found.update(PLACEHOLDER_RE.findall(text))
    return sorted(found)


def device_packages(adb, serial):
    rc, out, err = kit.adb_shell(adb, serial, "pm list packages", timeout=30)
    if rc != 0:
        print("读取包名失败: %s" % (err or out).strip()[:120], file=sys.stderr)
        return []
    return sorted(line.strip()[len("package:"):] for line in out.splitlines()
                  if line.startswith("package:"))


def load_existing(path):
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        return dict(data.get("aliases") or {})
    except (OSError, ValueError):
        return {}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--serial")
    ap.add_argument("--adb")
    ap.add_argument("--out", default=os.path.join(ROOT, "local.json"))
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--packages-file", help="离线：从文件读取包名（每行一个）")
    ap.add_argument("--set", action="append", default=[], metavar="PLACEHOLDER=PACKAGE")
    ap.add_argument("--refresh", action="store_true", help="忽略现有映射，全部重新匹配")
    args = ap.parse_args()

    placeholders = find_placeholders()
    if not placeholders:
        print("仓库里没有 com.vendor.* 占位名")
        return 0

    if args.packages_file:
        packages = [l.strip() for l in open(args.packages_file, encoding="utf-8") if l.strip()]
    else:
        adb = kit.resolve_adb(args.adb)
        serial = kit.pick_device(adb, args.serial)
        if not serial:
            print("没有设备；可用 --packages-file 离线生成")
            return 2
        packages = device_packages(adb, serial)
        if not packages:
            return 3

    overrides = {}
    for item in args.set:
        if "=" not in item:
            print("--set 需要 PLACEHOLDER=PACKAGE 形式: %r" % item, file=sys.stderr)
            return 2
        k, v = item.split("=", 1)
        overrides[k.strip()] = v.strip()

    existing = {} if args.refresh else load_existing(args.out)
    resolved, unresolved = {}, []
    for ph in placeholders:
        if ph in overrides:
            resolved[ph] = overrides[ph]
            continue
        if ph in existing:
            resolved[ph] = existing[ph]
            continue
        candidates = uiauto.suggest_packages(packages, ph, limit=3)
        if candidates:
            resolved[ph] = candidates[0]
        else:
            unresolved.append((ph, candidates))

    installed = set(packages)
    print("%-26s %-44s %s" % ("placeholder", "package", "status"))
    for ph in placeholders:
        if ph in resolved:
            pkg = resolved[ph]
            status = "ok" if pkg in installed else "不在设备上（检查映射）"
            print("%-26s %-44s %s" % (ph, pkg, status))
        else:
            print("%-26s %-44s %s" % (ph, "-", "未找到（--set 指定）"))

    if unresolved:
        print("\n未解析 %d 个占位名，请用 --set 指定" % len(unresolved), file=sys.stderr)
    if args.dry_run:
        print("\n(dry-run，未写入)")
        return 1 if unresolved else 0

    payload = {
        "_comment": "local placeholder -> real package names; generated by tools/make_local.py",
        "aliases": dict(sorted(resolved.items())),
    }
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("\n写入 %s（%d 条）" % (args.out, len(resolved)))
    return 1 if unresolved else 0


if __name__ == "__main__":
    sys.exit(main())